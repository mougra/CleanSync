/** Проверка полноты словаря в обе стороны: сид падает на ней, а не на живом плане. */
export const validateCatalogTranslations = (titles: readonly string[]): string[] => {
  const problems: string[] = [];

  for (const title of missingKeys(titles, CATALOG_TITLE_EN)) {
    problems.push(`нет английского перевода задачи «${title}»`);
  }

  for (const title of extraKeys(titles, CATALOG_TITLE_EN)) {
    problems.push(`английский перевод задачи «${title}» остался без оригинала`);
  }

  return problems;
};
