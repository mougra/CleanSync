/**
 * Зоны дома на английском.
 *
 * Зона — это не свободный текст пользователя, а словарь из каталога задач
 * (`services/taskCatalog.ts`) и сидов: «Кухня», «Ванная», «По всему дому».
 * Поэтому переводим её словарём, а не построчно: одна и та же зона встречается
 * в челленджах, привычках, каталоге и сгенерированных задачах, и все они должны
 * называться одинаково.
 *
 * Если зоны нет в словаре, возвращаем `null` — вызывающий код оставляет русское
 * значение: непереведённая зона лучше пустой (тот же принцип, что и в SQL
 * `COALESCE(перевод, оригинал)`).
 */
export const ZONE_EN: Record<string, string> = {
  Кухня: 'Kitchen',
  Ванная: 'Bathroom',
  Спальня: 'Bedroom',
  Детская: "Kids' room",
  Кабинет: 'Home office',
  Гостиная: 'Living room',
  Прихожая: 'Hallway',
  Балкон: 'Balcony',
  Двор: 'Yard',
  Гараж: 'Garage',
  Окна: 'Windows',
  'По всему дому': 'Whole home',
};

export const zoneEn = (zone: string | null | undefined): string | null => {
  if (!zone) {
    return null;
  }

  return ZONE_EN[zone] ?? null;
};
