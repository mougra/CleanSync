import type { DailyMinutesOption, PartialHomeAnswers } from './homePlan';

/**
 * Дневной бюджет сгенерированных задач — единственный источник правды для чисел.
 *
 * Анкета «Настройка по дому» отвечает на вопрос «сколько времени в день человек
 * готов тратить» (`dailyMinutes`), и по этому ответу считается один и тот же
 * дневной бюджет для **всех** генераторов сразу:
 *
 *  - постоянный набор «Мои задачи» (services/defaultTasks.ts) — ежедневный
 *    минимум, недельные дела и раскладка месячных по числам месяца;
 *  - недельный план «План по дому» (services/homePlan.ts) — он получает бюджет
 *    дня за вычетом того, что уже занято набором «Мои задачи».
 *
 * Почему таблица живёт отдельно. Раньше в двух генераторах были две разные
 * таблицы (в наборе — жёсткие 40 минут, в плане — 20/35/40/30), и каждый из них
 * по отдельности держался своего лимита, а сумма в дне выходила за любой из них:
 * на живом пользователе с ответом «минимум, 20-30 минут в день» получалось
 * 12 + 22 + 19 = 53 минуты в понедельник. Числа бюджета обязаны лежать в одном
 * месте, иначе расхождение вернётся при первой же правке.
 *
 * Что считается в бюджет, а что нет. Бюджет ограничивает **только генерацию**:
 * задачи, которые человек создал сам (source пустой или свой), в него не
 * входят и просто добавляются сверх. Ничего при этом не скрывается и не
 * блокируется в интерфейсе — бюджет влияет на то, что предлагает сервер, а не
 * на то, что видит и делает человек (правило 2 заказчика).
 */

/**
 * Абсолютный потолок дневной нагрузки сгенерированных задач.
 *
 * Бюджет по ответу никогда его не превышает: «1-2 часа» в анкете — это
 * готовность человека, а не разрешение вывалить на него всю квартиру за день.
 * Дела каталога раздроблены до 3-25 минут, поэтому и «убрать всё за раз»
 * в 40 минут не помещается: лишнее уходит в summary.droppedTasks, а не в
 * перегруз.
 */
export const MAX_DAILY_MINUTES = 40;

/**
 * Ответ анкеты → дневной бюджет сгенерированных задач в минутах.
 *
 * Значения утверждены заказчиком: under30 → 25, 30to60 → 40, 1to2h → 40,
 * depends → 30. Это бюджет **суммы** всех сгенерированных дел дня, а не
 * отдельного генератора.
 */
export const DAY_BUDGET_MINUTES: Record<DailyMinutesOption, number> = {
  under30: 25,
  '30to60': 40,
  '1to2h': 40,
  depends: 30,
};

/**
 * Дневной бюджет по ответам анкеты.
 *
 * Значение из таблицы дополнительно зажато потолком MAX_DAILY_MINUTES: если в
 * таблицу однажды попадёт большее число, инвариант «не больше 40 минут в день»
 * всё равно останется в силе (см. scripts/check-default-tasks.ts).
 *
 * Принимает и полные ответы, и частичные: незаполненный шаг берёт бюджет
 * значения по умолчанию — ровно так же, как его трактует генератор
 * (withDefaultAnswers, services/homePlan.ts).
 */
export const dayBudget = (answers: PartialHomeAnswers): number => {
  const option = answers.dailyMinutes ?? '30to60';

  return Math.min(DAY_BUDGET_MINUTES[option], MAX_DAILY_MINUTES);
};

/** Одна сгенерированная задача в объёме, нужном для расчёта занятости дня. */
export interface GeneratedTaskLike {
  frequency: string;
  minutes: number;
  dayOfWeek: number | null;
}

/** Набор сгенерированных задач: structural, чтобы не тянуть типы генератора. */
export interface GeneratedTaskSetLike {
  tasks: readonly GeneratedTaskLike[];
}

/**
 * Сколько минут **сгенерированных** задач уже занимает каждый день недели.
 *
 * Считается по тому, что реально попадает в «Сегодня»: ежедневный минимум плюс
 * недельные дела этого дня. Месячные и более редкие дела в карту не входят — их
 * нагрузка привязана к числу месяца, а не к дню недели, и учитывается при
 * раскладке по числам внутри самих генераторов.
 *
 * Вычитая эту карту из бюджета дня, недельный план получает свой остаток: два
 * генератора перестают складывать минуты поверх общего лимита.
 */
export const occupiedMinutesByWeekday = (set: GeneratedTaskSetLike): Map<number, number> => {
  const daily = set.tasks
    .filter((task) => task.frequency === 'daily')
    .reduce((sum, task) => sum + task.minutes, 0);

  const occupied = new Map<number, number>();

  for (let day = 0; day <= 6; day += 1) {
    const weekly = set.tasks
      .filter((task) => task.frequency === 'weekly' && task.dayOfWeek === day)
      .reduce((sum, task) => sum + task.minutes, 0);

    occupied.set(day, daily + weekly);
  }

  return occupied;
};
