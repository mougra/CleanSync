/**
 * Каталог задач уборки для мастера «Настройка по дому».
 *
 * Это библиотека, из которой генератор (backend/services/homePlan.ts) собирает
 * недельный план: задачи фильтруются по уровню и тегам ответов пользователя и
 * раскладываются по выбранным дням под дневной бюджет времени.
 *
 * Почему каталог в коде, а не в таблице: тексты задач — это контент, который
 * меняется вместе с генератором, а не данные пользователя. Схему БД без
 * необходимости не расширяем (backend/migrations), а сид (`backend/seed.ts`)
 * импортирует каталог и проверяет его целостность.
 *
 * Правила наполнения:
 *  - формулировка короткая и конкретная («Протереть подоконник на кухне»),
 *    без общих слов вроде «убраться» и «навести порядок»;
 *  - `room` — зона из того же словаря, что в сидах челленджей и привычек
 *    (Кухня, Ванная, Спальня, Гостиная, Прихожая, Детская, Кабинет, Балкон,
 *    Двор, Гараж, По всему дому) — по ней же считается «какие зоны задействованы»;
 *  - `minutes` — реальная оценка, а не «среднее по больнице»: от неё зависит,
 *    влезет ли задача в дневной бюджет (25/55/110/45 минут);
 *  - `level` — во сколько сил задача обходится: light (быстрая, 5-15 минут),
 *    normal (обычное дело, 15-40), deep (трудозатратное, 25-70: ковры, окна,
 *    расхламление, техника);
 *  - тег `pets`/`balcony`/`yard`/`garage`/`kids`/`office` включает задачу только
 *    при соответствующем ответе анкеты; теги `laundry` + `dry_air`/`dry_machine`
 *    привязывают стирку к способу сушки; `seasonal`, `declutter`, `carpets`,
 *    `windows` — тематические подборки.
 */

