let cachedCatalog: CatalogTask[] | null = null;

/**
 * Каталог задач. Собирается из компактных строк один раз за процесс.
 * Тегов может быть несколько: 'kids,carpets'.
 */
export const getTaskCatalog = (): CatalogTask[] => {
  if (cachedCatalog) {
    return cachedCatalog;
  }

  cachedCatalog = CATALOG_ROWS.map(([task, room, minutes, level, tags, cadence]) => ({
    task,
    room,
    minutes,
    level,
    tags: tags ? (tags.split(',') as TaskTag[]) : [],
    cadence,
  }));

  return cachedCatalog;
};

