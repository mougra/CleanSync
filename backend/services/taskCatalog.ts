/** Средняя длительность задачи: по ней видно, раздроблен каталог или нет. */
export const taskCatalogAverageMinutes = (): number => {
  const catalog = getTaskCatalog();

  if (catalog.length === 0) return 0;

  const total = catalog.reduce((sum, item) => sum + item.minutes, 0);

  return Math.round((total / catalog.length) * 10) / 10;
};

/**
 * Проверка целостности каталога для сида: дубли названий, пустые поля,
 * неизвестные теги, слишком длинные задачи и нулевые минуты ломают генераторы
 * незаметно, поэтому лучше падать на `npm run seed`, чем на живом плане.
 *
 * Отсутствие тегов — это норма, а не ошибка: задача без тегов подходит всем
 * (протереть столешницу можно в любом доме), а теги лишь включают задачу при
 * определённом ответе анкеты.
 */
export const validateTaskCatalog = (): string[] => {
  const problems: string[] = [];
  const seenTitles = new Set<string>();
  const knownTags = new Set(Object.keys(TASK_TAG_LABELS));
  const knownCadences = new Set(Object.keys(TASK_CADENCE_LABELS));

  for (const item of getTaskCatalog()) {
    if (!item.task.trim()) problems.push('Пустое название задачи');
    if (!item.room.trim()) problems.push(`Без зоны: ${item.task}`);
    if (!Number.isFinite(item.minutes) || item.minutes <= 0)
      problems.push(`Некорректное время: ${item.task}`);
    if (item.minutes > MAX_CATALOG_TASK_MINUTES)
      problems.push(
        `Задача длиннее ${MAX_CATALOG_TASK_MINUTES} минут (${item.minutes}): ${item.task} — раздробите её на шаги`
      );
    if (!['light', 'normal', 'deep'].includes(item.level))
      problems.push(`Неизвестный уровень у задачи: ${item.task}`);
    if (!knownCadences.has(item.cadence))
      problems.push(`Неизвестная периодичность «${item.cadence}»: ${item.task}`);

    for (const tag of item.tags) {
      if (!knownTags.has(tag)) problems.push(`Неизвестный тег «${tag}»: ${item.task}`);
    }

    if (seenTitles.has(item.task)) problems.push(`Дубль названия: ${item.task}`);
    seenTitles.add(item.task);
  }

  return problems;
};

/** Сколько задач каждого уровня — полезно видеть при наполнении каталога. */
export const taskCountByLevel = (): Record<TaskLevel, number> => {
  const counts: Record<TaskLevel, number> = { light: 0, normal: 0, deep: 0 };

  for (const item of getTaskCatalog()) {
    counts[item.level] += 1;
  }

  return counts;
};

/** Сколько задач каждой периодичности — для диагностики «Моих задач». */
export const taskCountByCadence = (): Record<TaskCadence, number> => {
  const counts: Record<TaskCadence, number> = {
    daily: 0,
    weekly: 0,
    biweekly: 0,
    monthly: 0,
    quarterly: 0,
    semiannual: 0,
    yearly: 0,
  };

  for (const item of getTaskCatalog()) {
    counts[item.cadence] += 1;
  }

  return counts;
};
