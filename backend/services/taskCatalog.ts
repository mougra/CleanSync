/**
 * Каталог задач уборки для мастера «Настройка по дому».
 *
 * Это библиотека, из которой собираются два набора:
 *  - недельный план (backend/services/homePlan.ts) — что делать на этой неделе;
 *  - повторяющиеся «Мои задачи» (backend/services/defaultTasks.ts) — постоянный
 *    список дел с периодичностью «раз в N дней/недель/месяцев».
 *
 * Почему каталог в коде, а не в таблице: тексты задач — это контент, который
 * меняется вместе с генератором, а не данные пользователя. Схему БД без
 * необходимости не расширяем (backend/migrations), а сид (`backend/seed.ts`)
 * импортирует каталог и проверяет его целостность.
 *
 * Правила наполнения:
 *  - «одна запись = один простой шаг на 10-20 минут»: длинные дела разбиты на
 *    конкретные действия («протереть фасады», «вымыть плиту», «разобрать
 *    раковину»), а не сформулированы как «вымыть кухню»;
 *  - `minutes` — реальная оценка одного шага: 3-10 у ежедневных мелочей,
 *    10-20 у обычных дел, не больше MAX_CATALOG_TASK_MINUTES (25) ни у кого —
 *    потолок проверяет validateTaskCatalog на `npm run seed`;
 *  - `level` — во сколько сил задача обходится: light (быстрая, до 15 минут),
 *    normal (обычное дело), deep (трудозатратное: ковры, окна, духовка,
 *    расхламление);
 *  - `cadence` — периодичность по умолчанию для «Моих задач»: daily, weekly,
 *    biweekly, monthly, quarterly (раз в 3 месяца), semiannual (раз в полгода),
 *    yearly. В базу она превращается в пару (frequency, interval_count);
 *  - `room` — зона из того же словаря, что в сидах челленджей и привычек
 *    (Кухня, Ванная, Спальня, Гостиная, Прихожая, Детская, Кабинет, Балкон,
 *    Двор, Гараж, По всему дому) — по ней же считается «какие зоны задействованы»;
 *  - тег `pets`/`balcony`/`yard`/`garage`/`kids`/`office` включает задачу только
 *    при соответствующем ответе анкеты; теги `laundry` + `dry_air`/`dry_machine`
 *    привязывают стирку к способу сушки; `seasonal`, `declutter`, `carpets`,
 *    `windows` — тематические подборки; `floors` и `dust` помечают задачи про
 *    полы и пыль, чтобы генератор масштабировал их по числу комнат.
 */

export type TaskLevel = 'light' | 'normal' | 'deep';

export type TaskTag =
  | 'pets'
  | 'balcony'
  | 'yard'
  | 'garage'
  | 'kids'
  | 'office'
  | 'seasonal'
  | 'declutter'
  | 'carpets'
  | 'windows'
  | 'laundry'
  | 'dry_air'
  | 'dry_machine'
  | 'floors'
  | 'dust';

/** Периодичность по умолчанию: как часто задача повторяется в «Моих задачах». */
export type TaskCadence =
  | 'daily'
  | 'weekly'
  | 'biweekly'
  | 'monthly'
  | 'quarterly'
  | 'semiannual'
  | 'yearly';

