/**
 * Словарь зон дома.
 *
 * Зона — это часть словаря, а не свободный текст: «Кухня», «Ванная», «По всему
 * дому». В базе зона лежит русским названием (так она и была заведена, и по ней
 * же считаются срезы в статистике и на главной), а интерфейс переводит её через
 * i18n по коду: `tasks.zone.kitchen` и так далее.
 *
 * Зачем код на входе. Раньше форма задачи подставляла в `tasks.room` уже
 * переведённую подпись (`t('tasks.zone.kitchen')`), и в англоязычном интерфейсе
 * в базу попадало «Kitchen»: группировка по зонам, статистика и словарь
 * переводов переставали её узнавать. Теперь клиент присылает код, а каноничное
 * название подставляет сервер.
 *
 * Свободный текст не трогаем: пользователь может вписать свою зону, и она
 * остаётся как есть — переводить её нечем и не нужно.
 */
export const ZONE_CANONICAL: Record<string, string> = {
  kitchen: 'Кухня',
  bathroom: 'Ванная',
  bedroom: 'Спальня',
  livingRoom: 'Гостиная',
  hallway: 'Прихожая',
  kidsRoom: 'Детская',
  office: 'Кабинет',
  balcony: 'Балкон',
  yard: 'Двор',
  garage: 'Гараж',
  wholeHouse: 'По всему дому',
  windows: 'Окна',
};

/** Привести зону из запроса к словарю базы: код → русское название. */
export const canonicalZone = (value: unknown): string | null => {
  if (typeof value !== 'string') {
    return null;
  }

  const trimmed = value.trim();

  if (!trimmed) {
    return null;
  }

  return ZONE_CANONICAL[trimmed] ?? trimmed;
};
