import { defineConfig } from 'vitest/config';

/**
 * Настройки тестов API.
 *
 * Таймаут поднят с пяти секунд по умолчанию: раскладка плана (`buildBasePlan`)
 * считает занятость дней перебором вариантов, и на полном профиле дома один
 * прогон занимает секунды, а тест делает их несколько. Пять секунд на CI-раннере
 * не хватало, и тесты падали по времени, а не по существу — проверка «день не
 * пустой» ждала 60 дней на каждое дело.
 *
 * Это не замена оптимизации: если раскладка начнёт занимать минуты, чинить надо
 * её, а не таймаут.
 */
export default defineConfig({
  test: {
    /*
     * Один поток, а не пул. Тяжёлые тесты раскладки считают план по 10–15 секунд
     * синхронно, и пул на этом падает с «Timeout calling onTaskUpdate»: тест
     * проходит, но прогон завершается ошибкой. В одном потоке отчёта о задачах
     * через RPC нет, и прогон честно зелёный.
     */
    pool: 'threads',
    poolOptions: { threads: { singleThread: true } },
    testTimeout: 180_000,
    hookTimeout: 60_000,
  },
});
