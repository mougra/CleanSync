-- Up Migration
-- Память об отказах: названия сгенерированных задач, которые человек удалил.
--
-- Зачем. Набор «Мои задачи» идёт из одного источника (services/defaultTasks.ts)
-- и пересобирается идемпотентно: недостающие дела добавляются заново. Пока задач
-- было две штуки, это не мешало, но у набора есть обратная сторона — удалённая
-- сгенерированная задача возвращалась при следующей пересборке или повторном
-- прохождении анкеты, потому что ключ идемпотентности — название внутри
-- расписания (syncDefaultTasks в routes/homeProfile.ts). Для человека это
-- выглядело так, будто кнопка «удалить» не работает.
--
-- Что здесь лежит. Одна строка — одно удалённое название: (user_id, title).
-- Название хранится так, как оно было в базе (title задачи), а сравнение при
-- сборке идёт нормализованным (обрезанные пробелы и регистр) — правило одно на
-- весь проект, помощник `normalizeTaskTitle` в services/defaultTasks.ts.
--
-- Кто пишет:
--   * DELETE /api/tasks/:id (routes/tasks.ts) — и только для сгенерированных
--     задач (source IN ('home_profile_defaults', 'home_plan')). Свою задачу
--     человек удаляет без следа в этом списке: её никто и не воскрешал бы.
--   * DELETE /api/home-profile (сброс анкеты) — наоборот, очищает список: раз
--     человек начинает настройку заново, прежние отказы больше не действуют.
--
-- Ограничения. Первичный ключ (user_id, title) делает запись идемпотентной:
-- повторное удаление того же названия ничего не меняет (ON CONFLICT DO NOTHING).
-- Внешний ключ с ON DELETE CASCADE обязателен: без него удаление пользователя
-- (в том числе DELETE /api/auth/account) падало бы на осиротевших строках, а
-- тесты и разовые скрипты чистят за собой именно так.
CREATE TABLE IF NOT EXISTS dismissed_default_tasks (
  user_id INT NOT NULL,
  title TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, title),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Индекс по user_id: первичный ключ начинается с user_id и уже годится для
-- выборки «все отказы пользователя», но отдельный индекс делает это явным и
-- дешёвым для планировщика (миграция 0010 сделана по тому же принципу).
CREATE INDEX IF NOT EXISTS idx_dismissed_default_tasks_user_id
  ON dismissed_default_tasks(user_id);

-- Down Migration
-- Откат убирает только эту таблицу: список отказов — производная информация от
-- задач, её можно потерять без последствий для остальных данных.
DROP INDEX IF EXISTS idx_dismissed_default_tasks_user_id;
DROP TABLE IF EXISTS dismissed_default_tasks;
