-- Up Migration
-- Периодичность задач переходит на единую единицу измерения — день.
--
-- Зачем. Раньше `interval_count` значил разное в зависимости от `frequency`:
-- у недельной задачи — число недель (1, 2, 3, 6), у месячной — число месяцев
-- (1, 2, 3, 6, 12, 18, 36). Заказчик попросил выражать периодичность **в днях**:
-- недельные ступени стали 7/14/21/42, месячные — 30/60/90/120/180, а годовое дело
-- каталога — 180 дней (полгода, верхняя граница сгенерированного цикла).
-- Генератор и каталог уже переведены (backend/services/defaultTasks.ts:
-- CADENCE_DAYS), а строки, созданные до этого, ещё лежат в прежних единицах: без
-- конвертации «раз в 3 недели» читалось бы как «раз в 3 дня», а «раз в 2 месяца» —
-- как «раз в 2 дня».
--
-- Что конвертируем. Ровно те значения, которые порождал прежний код, — по
-- диапазону, а не «всё подряд»: у недельных это 1…6 недель, у месячных — 1, 2, 3,
-- 6, 12, 18 и 36 месяцев. Остальные значения считаются уже дневными и остаются
-- как есть. Проверка на диапазон важна и для самой миграции: она безопасна при
-- повторном запуске — после первого прохода значений 1…6 у недельных задач не
-- остаётся (самое частое стало 7), поэтому второй запуск ничего не меняет.
--
-- Почему диапазон, а не «только сгенерированные». Свою задачу человек тоже мог
-- завести «раз в 3 недели» (форма писала `weekly` + счётчик), и такие строки
-- нужно перевести так же: у них ровно тот же прежний смысл. Источник
-- (`home_profile_defaults` / `home_plan`) для этого не нужен, а его участие
-- оставило бы часть старых строк в неделях — то есть половину задачи нерешённой.
--
-- Почему месячное «18» превращается в 540 дней, а не в «18 месяцев». Прежний
-- генератор подставлял `interval_count` месяцами с шагом 30 дней на месяц, и в
-- базе от «18 месяцев» осталось только число 18. Умножение на 30 возвращает
-- ровно тот срок, которым эта строка и была: 540 дней. Точный календарный счёт
-- тут невозможен — разница между 30 днями и календарным месяцем накапливается
-- внутри выборки, а не в этом числе.
UPDATE tasks
   SET interval_count = interval_count * 7
 WHERE frequency = 'weekly'
   AND interval_count BETWEEN 1 AND 6;

UPDATE tasks
   SET interval_count = interval_count * 30
 WHERE frequency = 'monthly'
   AND interval_count IN (1, 2, 3, 6, 12, 18, 36);

