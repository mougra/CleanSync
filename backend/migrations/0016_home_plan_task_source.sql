-- Up Migration
-- Пометка источника у задач недельного плана «План по дому».
--
-- Зачем. Расписание «План по дому» целиком собирает сервер
-- (POST /api/home-profile/plan → savePlan в backend/routes/homeProfile.ts):
-- прежний план вместе с задачами удаляется, новый создаётся заново. До этой
-- миграции `savePlan` не заполнял `tasks.source`, поэтому 18 задач плана ничем
-- не отличались от задач, созданных человеком руками. Пометка нужна, чтобы
-- сгенерированное было отличимо от своего: без неё нельзя ни пересобирать план
-- точечно, ни считать статистику по источникам, ни проверить инвариант
-- «суммарная сгенерированная нагрузка дня не больше бюджета» — а именно на нём
-- держится дневной бюджет из services/dailyBudget.ts.
--
-- Почему бэкфилл корректен и безопасен. Расписание с названием «План по дому»
-- создаётся ровно одним местом — `savePlan`, и это расписание всегда личное
-- (user_id заполнен, household_id NULL), в отличие от общего плана дома. Оно
-- никогда не бывает пользовательским: пользователь может править и удалять
-- задачи внутри, но само расписание и его строки рождаются только генератором.
-- Поэтому задачи этого расписания с пустым `source` — это в точности задачи
-- старого плана, и проставить им `home_plan` можно без риска задеть что-то
-- созданное руками. Сравнение `title` точное, регистр и пробелы не трогаем:
-- заголовок задаёт константа PLAN_TITLE в routes/homeProfile.ts, и она же
-- используется при поиске прошлого плана при каждой пересборке.
--
-- Условие `source IS NULL` (а не «любое значение») намеренно: набор «Мои задачи»
-- помечен своим `home_profile_defaults` (миграция 0012), и перезаписывать его
-- нельзя даже гипотетически. Пустая строка тоже пропускается — такого значения
-- в колонке быть не должно, а если оно появилось, это уже не наш случай.
UPDATE tasks
   SET source = 'home_plan'
 WHERE source IS NULL
   AND schedule_id IN (
     SELECT id FROM schedules WHERE title = 'План по дому'
   );

-- Down Migration
-- Обратная операция снимает пометку только с задач этого расписания: прежнее
-- состояние колонки — NULL (до миграции `savePlan` её не заполнял). Задачи
-- «Моих задач» с `home_profile_defaults` не затрагиваются.
UPDATE tasks
   SET source = NULL
 WHERE source = 'home_plan'
   AND schedule_id IN (
     SELECT id FROM schedules WHERE title = 'План по дому'
   );
