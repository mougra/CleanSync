--
-- Зачем. Он обещал то, чего план не даёт: дневной бюджет упирается в общий потолок
-- 40 минут (services/dailyBudget.ts), поэтому «1-2 часа» и «30-60 минут» давали
-- один и тот же день на практике, а человек, выбравший больше, видел 22 минуты в
-- среднем и справедливо считал, что получил мало. Заказчик попросил убрать
-- непонятный вариант, и это правильно: обещать час и выдавать сорок минут — хуже,
-- чем не предлагать такой выбор.
--
-- Что делаем с существующими профилями. Переводим их на «30-60 минут»: это ровно
-- то поведение, которое они и получали (потолок 40 минут в день), так что ничего
-- в их плане не меняется. Числа бюджета для старого значения остаются в коде как
-- устаревший псевдоним — на случай, если строка со старым ответом ещё где-то
-- лежит; выдумывать из-за этого падение нельзя.
UPDATE home_profiles SET daily_minutes = '30to60' WHERE daily_minutes = '1to2h';

