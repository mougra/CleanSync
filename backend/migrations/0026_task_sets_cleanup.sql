-- Заказчик попросил убрать дубли и лишние дела из списка, который видит человек:
--  - три задачи про дверь («дверные ручки и домофон», «дверь и ручку изнутри»,
--    «дверь и выключатель в кабинете») сливаются в одну;
--  - «Поменять наволочки и прогладить их», «Заменить батарейки…», «Пропылесосить
