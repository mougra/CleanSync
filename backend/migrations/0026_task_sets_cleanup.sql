-- Трогаем только строки, которые создал генератор (`home_profile_defaults`):
-- свои задачи человека с такими же названиями миграция не удаляет и не меняет.
-- Уже существующие наборы пересобираются не сразу (пересборка — явное действие
-- в мастере), поэтому правку данных делаем здесь, иначе список остался бы старым.

-- 1. Три двери → одно дело. Оставляем самую раннюю строку пользователя.
WITH door AS (
  SELECT id,
         row_number() OVER (PARTITION BY user_id ORDER BY id) AS rn
  FROM tasks
  WHERE source = 'home_profile_defaults'
    AND title IN (
      'Протереть дверные ручки и домофон',
      'Протереть дверь и ручку изнутри',
      'Протереть дверь и выключатель в кабинете'
    )
)
UPDATE tasks AS t
SET title = 'Протереть входную дверь и домофон',
    room = 'Прихожая',
    estimated_minutes = 15,
    frequency = 'monthly',
    interval_count = 1,
    day_of_week = NULL,
    day_of_month = EXTRACT(DAY FROM COALESCE(t.due_date, CURRENT_DATE))::int,
    month_shifts = NULL
FROM door
WHERE t.id = door.id AND door.rn = 1;

DELETE FROM tasks
WHERE source = 'home_profile_defaults'
  AND title IN (
    'Протереть дверные ручки и домофон',
    'Протереть дверь и ручку изнутри',
    'Протереть дверь и выключатель в кабинете'
  );

-- 2. Лишние дела: наволочки, батарейки, пылесос по шторам.
DELETE FROM tasks
WHERE source = 'home_profile_defaults'
  AND title IN (
    'Поменять наволочки и прогладить их',
    'Заменить батарейки в беспроводной мыши',
    'Проверить батарейки в пультах и часах',
    'Заменить батарейки в датчиках',
    'Пропылесосить шторы и тюль'
  );

-- 3. Датчики проверяем без упоминания батареек.
UPDATE tasks
SET title = 'Проверить дымовые датчики'
WHERE source = 'home_profile_defaults'
  AND title = 'Проверить дымовые датчики и батарейки';

-- 4. Шторы и тюль — раз в год (частота хранится в днях).
UPDATE tasks
SET frequency = 'yearly', interval_count = 1
WHERE source = 'home_profile_defaults'
  AND title IN ('Постирать шторы в комнатах', 'Постирать тюль в гостиной');

-- 5. Память об отказах: переименованные названия не должны воскрешать старые
--    строки при следующей пересборке, а удалённые — висеть мусором.
--    Сначала снимаем возможные коллизии: если у человека уже есть отказ на новое
--    название, старые строки удаляем, иначе unique (user_id, title) не даст
--    переименовать.
DELETE FROM dismissed_default_tasks AS d
USING dismissed_default_tasks AS k
WHERE d.user_id = k.user_id
  AND d.title IN (
    'Протереть дверные ручки и домофон',
    'Протереть дверь и ручку изнутри',
    'Протереть дверь и выключатель в кабинете'
  )
  AND k.title = 'Протереть входную дверь и домофон';

UPDATE dismissed_default_tasks
SET title = 'Протереть входную дверь и домофон'
WHERE title IN (
