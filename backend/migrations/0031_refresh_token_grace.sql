-- Up Migration
-- Льготное окно для refresh-токена.
--
-- Токен меняется (ротация) при каждом обновлении сессии, и строка в таблице
-- заменяется новой. Когда сессию обновляют одновременно два клиента — вкладка и
-- серверный рендер, две вкладки, приложение и браузер, — второй приходит со
-- старым токеном уже после того, как первый его обменял. Раньше это был 401:
-- «сессия истекла», хотя она жива, и человек вылетал из аккаунта без причины.
--
-- `prev_token` помнит прежнее значение, `rotated_at` — когда произошёл обмен.
-- В течение пары минут после обмена старый токен ещё принимается: клиент
-- получает свежий access и **текущий** refresh из базы, то есть его cookie
-- лечится на месте. Дольше окно не нужно: это защита от гонки, а не второй
-- полноценный токен.
ALTER TABLE refresh_tokens
  ADD COLUMN IF NOT EXISTS prev_token TEXT,
  ADD COLUMN IF NOT EXISTS rotated_at TIMESTAMPTZ;

-- Down Migration
ALTER TABLE refresh_tokens
  DROP COLUMN IF EXISTS rotated_at,
  DROP COLUMN IF EXISTS prev_token;
