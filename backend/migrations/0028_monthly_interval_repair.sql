-- Up Migration
-- Починка периодичности, которую миграция 0026 поставила неверно.
--
-- После 0022 интервал у всех частот хранится в **днях**: «раз в месяц» — это
-- `interval_count = 30`, «раз в год» — 360. Миграция 0026 слила три «дверных»
-- дела в одно и поставила `frequency = 'monthly', interval_count = 1` — значение
-- из прежней семантики, где интервал был множителем частоты.
--
-- Последствие: выборка «Сегодня» и календарь считают месячный цикл как
-- `MOD(разница_месяцев, interval_count / 30)`, а `1 / 30` в целочисленном
-- делении даёт ноль — деление на ноль роняет весь запрос. В интерфейсе это
-- выглядит как пустой план дня и пропавшие кольца прогресса в календаре.
--
-- Правим только заведомо неверные строки: у месячных дел интервал меньше 30 дней
-- не встречается ни в каталоге, ни в формах (там шкала «месяц» даёт 30, 60, …).
UPDATE tasks
SET interval_count = 30
WHERE frequency = 'monthly'
  AND interval_count < 30;

