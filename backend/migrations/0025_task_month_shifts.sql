-- Сдвиги редких дел по месяцам: `month_shifts[m]` — на сколько дней перенести
-- дело в месяце m (1–12), чтобы оно не попало в день, где сумма задач превышает
-- 40 минут.
--
-- Зачем. Частоты зафиксированы заказчиком, а редкое дело стоит на одном числе
-- месяца. День недели у числа за год проходит все семь, поэтому рано или поздно
-- дело попадает на день с недельными делами. Перенести такое вхождение на
-- соседний день — единственный способ держать потолок 40, не меняя частоту.
--
-- NULL — сдвигов нет (обычный случай). Значения считает планировщик
-- (`services/basePlan.ts`), а выборка «Сегодня» (`routes/tasks.ts`) применяет их
-- при чтении: эффективное число = `day_of_month + month_shifts[месяц]`.
ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS month_shifts smallint[];

