/**
 * Словари интерфейса — часть бандла, а не отдельный запрос.
 *
 * `@nuxtjs/i18n` v10 по умолчанию подгружает файлы локалей лениво: клиент после
 * старта делает `GET /_i18n/<hash>/<locale>/messages.json` и мержит ответ в
 * vue-i18n. Ошибку этого запроса модуль только пишет в консоль
 * (`Failed to load messages…`) и не повторяет, поэтому приложение монтируется с
 * пустыми сообщениями, и `t()` показывает сырые ключи (`nav.habits`) вместо
 * подписей — до перезагрузки страницы. Ловилось это после возврата в долго
 * открытую вкладку и после восстановления вкладок: в момент загрузки сеть может
 * быть ещё не готова, а сервер — перезапускаться при деплое.
 *
 * Здесь словари импортируются как обычный JSON, поэтому они попадают в общий
 * бандл (и в серверный, и в клиентский): к моменту гидратации `messages` уже на
 * месте, сеть для переводов не нужна вовсе. Поэтому же в `nuxt.config.ts` у
 * локалей убран `file` — иначе модуль продолжит генерировать загрузчики и делать
 * тот же запрос, только уже без пользы.
 *
 * Цена — ~28 КБ gzip (ru + en) в первой загрузке вместо ~27 КБ отдельного JSON;
 * разница в том, что бандл кэшируется вместе с приложением и не может «не
 * приехать». Файлы `locales/*.json` остаются источником правды: правка идёт там.
 */
import ru from './locales/ru.json';
import en from './locales/en.json';

export default defineI18nConfig(() => ({
  messages: { ru, en },
}));
