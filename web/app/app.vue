<script setup lang="ts">
// Сессия подтягивается один раз за рендер: на сервере — чтобы страница сразу
// знала пользователя, на клиенте — из payload без повторного запроса.
const auth = useAuthStore();
await useAsyncData('auth-session', () => auth.fetchSession());

/**
 * Сессия: серверный рендер мог отрисовать гостя, хотя refresh-cookie жива.
 *
 * Причин две. Access-cookie живёт 15 минут, и сервер восстанавливает сессию сам
 * (`server/plugins/restore-session.ts`) — но если обновить не удалось (гонка с
 * другой вкладкой, сеть), остаётся гостевая страница. Вторая причина — cookie,
 * выданные прежней версией приложения: они жили только на пути `/api/auth` и до
 * запроса страницы не доходили (см. `backend/cookies.ts`).
 *
 * Поэтому один раз, уже в браузере, пробуем восстановить сессию: `useApi` умеет
 * обновить её и повторить `/api/auth/me`. Гостю это стоит одного лишнего запроса
 * и ничего не меняет, а человек с живой сессией не остаётся «вышедшим».
 */
onMounted(async () => {
  if (auth.isAuthenticated) {
    return;
  }

  // Сессия восстановилась — но данные страниц уже успели прийти гостевыми
  // (плана дня и прогресса у гостя нет). Перечитываем их, иначе человек увидит
  // пустой план при живом аккаунте.
  if (await auth.fetchSession()) {
    await refreshNuxtData();
  }
});

// Язык, dir и hreflang для SEO: в i18n v10 все они включены по умолчанию
// (lang/dir/seo), поэтому вызов без опций.
const head = useLocaleHead();
useHead(() => head.value);

// Canonical и og:url: модуль nuxt-seo их в нашей связке не доносит до разметки
// (см. комментарий в composables/useCanonical.ts).
useCanonical();

// Значения по умолчанию для соцсетей: без своей картинки страница
// не покажет превью при шаринге. Страницы со своей обложкой перекрывают это.
useSeoMeta({
  ogSiteName: 'TidyPlan',
  // Картинка бренда по умолчанию: страницы со своей обложкой её перекрывают
  ogImage: '/og-image.png',
});

/**
 * Манифест выбираем по языку интерфейса.
 *
 * Русский манифест собирает @vite-pwa/nuxt из `pwa.manifest` в nuxt.config
 * (в dev его подменяет такой же файл из public), английский лежит готовым
 * файлом `public/manifest.en.webmanifest`. Разница не косметическая: в манифесте
 * живут описание и названия ярлыков, и на английском интерфейсе они должны быть
 * английскими. `id` в обоих файлах один — иначе система поставит второе
 * приложение рядом с первым.
 */
const { locale } = useI18n();
const api = useApi();

/**
 * Язык профиля.
 *
 * Переключатель меняет интерфейс и cookie, но письма и push-напоминания
 * собираются на сервере, где cookie не видно: там язык берётся из профиля.
 * Поэтому синхронизируем его при каждом изменении языка — и при входе тоже,
 * чтобы профиль соответствовал тому, что человек видит.
 */
watch(
  [locale, () => auth.isAuthenticated],
  () => {
    if (import.meta.server || !auth.isAuthenticated) {
      return;
    }

    void api
      .request('/api/auth/locale', {
        method: 'PUT',
        body: {
          locale: locale.value,
          // Часовой пояс нужен напоминаниям: «в 9:00» должно считаться
          // по времени человека, а не сервера.
          timezone: Intl.DateTimeFormat().resolvedOptions().timeZone,
        },
      })
      // Смена языка в интерфейсе не должна ломаться из-за сети: профиль
      // догонит при следующем переключении или входе.
      .catch(() => undefined);
  },
  { immediate: true },
);

/**
 * Тексты из базы — такая же часть языка, как подписи из словарей.
 *
 * Названия достижений, челленджей и привычек приходят из API на языке запроса,
 * и переключатель их сам не обновляет: страница остаётся смонтированной (одна
 * и та же компонента живёт и на `/achievements`, и на `/en/achievements`),
 * а `useAsyncData` в состоянии `success` второй раз данные не запрашивает —
 * на английском экране оставались русские названия. Перезапрашиваем всё, что
 * уже загружено; язык запроса `useApi` прочитает из нового cookie сам.
 */
watch(locale, (next, previous) => {
  if (import.meta.server || next === previous) {
    return;
  }

  void refreshNuxtData();
});

useHead(() => ({
  link: [
    {
      key: 'manifest',
      rel: 'manifest',
      href: locale.value === 'en' ? '/manifest.en.webmanifest' : '/manifest.webmanifest',
    },
  ],
}));
</script>

<template>
  <NuxtLayout>
    <NuxtPage />
  </NuxtLayout>
</template>
