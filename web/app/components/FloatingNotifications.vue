<!--
  Общий контейнер плавающих уведомлений: «Новое достижение» и «Задача удалена».

  Зачем контейнер, а не два независимых `position: fixed`. Уведомления могут быть
  видны одновременно: человек отмечает задачу, получает достижение, тут же удаляет
  строку — и две карточки оказывались бы на одном и том же пикселе, перекрывая
  друг друга. Здесь они лежат в одной колонке: место занимает только то, что
  реально показано (`v-if` внутри компонентов), а промежуток между ними задаёт
  `gap`. Сдвиг считает браузер, а не вторая формула с отступами — её пришлось бы
  держать в согласии с высотой чужой карточки.

  Отступ снизу. На телефоне кнопка «+» стоит на `--space-5` (24px) над нижней
  навигацией и занимает `--fab-size` (56px), то есть её верх — это
  `--nav-height + 80px`. Колонка уведомлений начинается ровно на этой высоте:
  карточка растёт вверх, поэтому кнопку она не закрывает (проверено замером рамок
  в headless Chrome на 390x844 и 1264x805). На десктопе та же формула с
  десктопным отступом кнопки — уведомления встают над ней.

  Баннер cookie на телефоне переехал наверх (`CookieBanner.vue`): внизу он
  делил бы те же 700-800 пикселей с кнопкой «+», уведомлениями и нижней
  навигацией — на узком экране они бы наложились друг на друга.
-->
<template>
  <div class="floating">
    <AchievementToast />
    <TaskUndoToast />
  </div>
</template>

<style scoped>
.floating {
  position: fixed;
  left: var(--space-4);
  right: var(--space-4);
  /*
   * Верх кнопки «+» — это её отступ от навигации плюс её высота:
   * `--nav-height + --space-5 + --fab-size`. Колонка уведомлений начинается ровно
   * там, поэтому карточка не ложится на кнопку (проверено замером рамок).
   */
  bottom: calc(var(--nav-height) + var(--space-5) + var(--fab-size) + env(safe-area-inset-bottom));
  z-index: 60;
  display: flex;
  flex-direction: column;
  gap: var(--space-3);
  /* Контейнер только расставляет карточки: клики по пустому месту не перехватываем */
  pointer-events: none;
}

.floating > * {
  pointer-events: auto;
}

@media (min-width: 768px) {
  /*
   * На десктопе нижней навигации нет, а правый нижний угол занят кнопкой «+»
   * (`--space-7` от края, высота `--fab-size`) — уведомления встают над ней.
   */
  .floating {
    left: auto;
    right: var(--space-5);
    bottom: calc(var(--space-7) + var(--fab-size) + var(--space-4));
    max-width: 380px;
  }
}
</style>
